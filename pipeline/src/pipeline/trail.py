"""The money trail: complaint -> clean issue -> work order -> contractor -> did it hold.

Every complaint ends up in exactly one issue. Issues BMC fixed are the work orders' linked complaints (duplicates included);
open and referred complaints are merged into issues by road, category and a 14-day window. Social posts are matched on place, topic
and timing. Nothing here is generated by a model: it is joins, rules and counts, so each link can be checked.
"""

import re

import numpy as np
import pandas as pd

from pipeline import config
from pipeline.audit import _inr, build_flags
from pipeline.data import load, write_json
from pipeline.issues import open_issues, prepare_complaints

REFERRED = ("Rejected - Not BMC road", "Forwarded to MMRDA/PWD", "Forwarded to SWM dept", "Rejected - Not road issue")
POST_WINDOW_BEFORE = pd.Timedelta(days=1)
POST_WINDOW_AFTER = pd.Timedelta(days=14)

TOPIC_CUES = [
    ("Broken paver blocks", re.compile(r"paver|tiles", re.I)),
    ("Open or broken manhole", re.compile(r"manhole|dhakkan|ढक्कन|मैनहोल", re.I)),
    ("Road cave-in", re.compile(r"dhas|sunk|sinkhole|cave", re.I)),
    ("Choked drain / nullah overflow", re.compile(r"gutter|nullah|drain|overflow|ghaan|sewage", re.I)),
    ("Pothole", re.compile(r"pothole|gaddha|gadda|khadda|खड्ड|गड्ढ", re.I)),
    ("Waterlogging", re.compile(r"waterlog|flood|paani|pani|पानी|पाणी|water|swimming pool", re.I)),
]
KIND_CUES = [
    ("thanks", re.compile(r"thank|shukriya|धन्यवाद|आभार", re.I)),
    ("repeat_claim", re.compile(r"\bback\b|phir se|again|punha|पुन्हा|फिर से|same story", re.I)),
    ("forward", re.compile(r"\bfwd\b|forward|as received|unverified", re.I)),
    ("sarcasm", re.compile(r"😂|swimming pool|mast |kya mast", re.I)),
]
COMPATIBLE = {"Waterlogging": {"Choked drain / nullah overflow"}, "Choked drain / nullah overflow": {"Waterlogging"}}


def post_kind(text: str) -> str:
    return next((k for k, p in KIND_CUES if p.search(text)), "complaint")


def post_topic(text: str) -> str | None:
    return next((t for t, p in TOPIC_CUES if p.search(text)), None)


def _fmt_date(ts) -> str:
    return f"{ts.day} {ts:%b}"


def _short(name: str) -> str:
    return name.replace(" (synthetic)", "")


def fixed_issues(c: pd.DataFrame, wo: pd.DataFrame, flags: pd.DataFrame, roads: pd.DataFrame) -> pd.DataFrame:
    """One issue per work order that has complaints linked: BMC's own link is the clean issue."""
    links = wo[["work_order_id", "linked_complaint_ids"]].dropna()
    links = links.assign(complaint_id=links.linked_complaint_ids.str.split("|")).explode("complaint_id")
    m = links.merge(c, on="complaint_id", how="left")
    g = m.groupby("work_order_id")
    iss = g.agg(
        n_complaints=("complaint_id", "size"),
        complaint_ids=("complaint_id", list),
        first_reported_at=("received_at", "min"),
        last_reported_at=("received_at", "max"),
        locality=("locality", lambda s: s.mode().iloc[0]),
        lat=("lat", "mean"),
        lon=("lon", "mean"),
        loc_lat=("loc_lat", "mean"),
        loc_lon=("loc_lon", "mean"),
        channels=("channel", lambda s: sorted(set(s))),
        languages=("language", lambda s: sorted(set(s))),
        upvotes=("upvotes", "sum"),
    ).reset_index()
    iss = iss.merge(wo, on="work_order_id")
    iss["lat"], iss["lon"] = iss.lat.fillna(iss.loc_lat), iss.lon.fillna(iss.loc_lon)
    iss["status"] = np.where(iss.reopened_within_30d == "Y", "fixed_failed", "fixed")
    iss["category"] = iss.work_type
    iss["road_name"] = iss.road_id.map(roads.road_name)
    by_wo = flags.groupby("work_order_id").flag_type.agg(lambda s: sorted(set(s)))
    iss["flag_types"] = iss.work_order_id.map(by_wo).map(lambda x: x if isinstance(x, list) else [])
    iss["work_order_ids"] = iss.work_order_id.map(lambda x: [x])
    iss["disposition"] = None
    return iss


def unfixed_issues(c: pd.DataFrame, roads: pd.DataFrame, statuses: tuple[str, ...], status: str, prefix: str) -> pd.DataFrame:
    iss = open_issues(c, statuses=statuses, prefix=prefix, drop_no_ward=False)
    iss = iss.rename(columns={"work_type": "category"})
    iss["locality"] = iss.canonical_locality
    iss["lat"], iss["lon"] = iss.lat.fillna(iss.loc_lat), iss.lon.fillna(iss.loc_lon)  # locality centre when no complaint had GPS
    iss["plan_issue_id"] = iss.issue_id if status == "never_fixed" else None  # the id the next-rupee plan uses for this issue
    iss["status"], iss["disposition"] = status, iss.pop("status")
    iss["road_name"] = iss.road_id.map(roads.road_name)
    iss["work_order_ids"] = [[] for _ in range(len(iss))]
    iss["flag_types"] = [[] for _ in range(len(iss))]
    return iss


def trail_text(r: pd.Series) -> str:
    n = int(r.n_complaints)
    channels = " and ".join(r.channels) if len(r.channels) <= 2 else f"{len(r.channels)} channels"
    head = f"{n} complaint{'s' if n > 1 else ''} about {r.category.lower()} near {r.locality} ({channels})"
    if r.status == "never_fixed":
        return f"{head}, no work order yet (status: {r.disposition})."
    if r.status == "not_bmc_scope":
        return f"{head}, not repaired by BMC ({r.disposition})."
    timing = ""
    if pd.notna(r.completed_at) and r.days_to_fix is not None and r.days_to_fix >= 0:
        timing = f", finished {_fmt_date(r.completed_at)}, {r.days_to_fix:.1f} days after the first complaint ({'within' if r.sla_met == 'Y' else 'after'} the {int(r.sla_hours)}-hour target)"
    held = "The repair failed within 30 days." if r.status == "fixed_failed" else "The repair held."
    flagged = f" Flagged for review: {', '.join(t.replace('_', ' ') for t in r.flag_types if t in ('over_billed', 'double_billed', 'dlp_paid'))}." if any(t in ("over_billed", "double_billed", "dlp_paid") for t in r.flag_types) else ""
    return f"{head} led to {r.work_order_id} by {_short(r.contractor_name)} ({r.repair_method.lower()}, {_inr(r.cost_inr)}){timing}. {held}{flagged}"


def link_social_posts(issues: pd.DataFrame, posts: pd.DataFrame, loc: pd.DataFrame, roads: pd.DataFrame) -> tuple[dict[str, list[str]], pd.DataFrame]:
    """Match each post to at most one issue by place, topic and timing. Returns issue_id -> post ids, and the posts with their kind.

    A post that names a locality is matched through the locality only: road names repeat across wards, so they are used
    just for posts that name no known locality.
    """
    posts = posts.copy()
    names = {}
    for _, r in loc.iterrows():
        for n in [r.locality] + (str(r.aliases).split(";") if pd.notna(r.aliases) else []):
            if n.strip():
                names[n.strip().lower()] = r.locality
    road_names = {n.lower(): n for n in roads.road_name.unique()}
    pattern = re.compile("|".join(re.escape(n) for n in sorted(names, key=len, reverse=True)), re.I)
    road_pattern = re.compile("|".join(re.escape(n) for n in sorted(road_names, key=len, reverse=True)), re.I)

    posts["kind"] = posts.text.map(post_kind)
    posts["topic"] = posts.text.map(post_topic)
    posts["places"] = posts.text.map(lambda t: {names[m.lower()] for m in pattern.findall(t)})
    posts["roads"] = posts.text.map(lambda t: {road_names[m.lower()] for m in road_pattern.findall(t)})

    issues = issues.assign(_end=issues[["last_reported_at", "completed_at"]].max(axis=1))
    by_place = issues.groupby("locality").indices
    by_road = issues[issues.road_name.notna()].groupby("road_name").indices
    linked: dict[str, list[str]] = {}
    matched = []
    for p in posts.itertuples():
        idx = {i for place in p.places for i in by_place.get(place, [])} if p.places else {i for road in p.roads for i in by_road.get(road, [])}
        topic = p.topic if isinstance(p.topic, str) else None  # missing topics arrive as NaN, which is truthy
        best, best_gap = None, None
        for i in idx:
            r = issues.iloc[i]
            if not (r.first_reported_at - POST_WINDOW_BEFORE <= p.posted_at <= r._end + POST_WINDOW_AFTER):
                continue
            if topic and topic != r.category and r.category not in COMPATIBLE.get(topic, set()):
                continue
            gap = abs((p.posted_at - r.first_reported_at).total_seconds())
            if best is None or gap < best_gap:
                best, best_gap = r.issue_id, gap
        matched.append(best)
        if best:
            linked.setdefault(best, []).append(p.post_id)
    posts["issue_id"] = pd.Series(matched, index=posts.index, dtype="object")
    return linked, posts


def build_trail() -> tuple[pd.DataFrame, dict]:
    flags, _ = build_flags()
    c = prepare_complaints()
    wo = load("work_orders")
    roads = load("roads").set_index("road_id")

    fixed = fixed_issues(c, wo, flags, roads)
    open_ = unfixed_issues(c, roads, config.OPEN_STATUSES, "never_fixed", "OI")
    referred = unfixed_issues(c, roads, REFERRED, "not_bmc_scope", "RF")
    iss = pd.concat([fixed, open_, referred], ignore_index=True)

    iss["completed_at"] = pd.to_datetime(iss.completed_at)
    iss["days_to_fix"] = ((iss.completed_at - iss.first_reported_at).dt.total_seconds() / 86400).where(iss.completed_at.notna())
    iss = iss.sort_values("first_reported_at").reset_index(drop=True)
    iss["issue_id"] = [f"ISS-{i + 1:04d}" for i in range(len(iss))]

    linked, posts = link_social_posts(iss, load("social_posts"), load("localities"), load("roads"))
    iss["social_post_ids"] = iss.issue_id.map(lambda i: linked.get(i, []))
    iss["trail"] = iss.apply(trail_text, axis=1)
    return iss, summarise(iss, c, posts)


def summarise(iss: pd.DataFrame, c: pd.DataFrame, posts: pd.DataFrame) -> dict:
    fixed = iss[iss.status.isin(["fixed", "fixed_failed"])]
    failed = fixed[fixed.status == "fixed_failed"]
    by_status = iss.groupby("status").agg(issues=("issue_id", "size"), complaints=("n_complaints", "sum")).to_dict("index")
    return {
        "complaints": len(c),
        "issues": len(iss),
        "complaints_per_issue": round(len(c) / len(iss), 2),
        "by_status": {k: {kk: int(vv) for kk, vv in v.items()} for k, v in by_status.items()},
        "fixed_issues_that_failed_pct": round(len(failed) / len(fixed), 3),
        "spend_on_fixed_inr": int(fixed.cost_inr.sum()),
        "spend_on_failed_inr": int(failed.cost_inr.sum()),
        "median_days_to_fix": round(float(fixed.days_to_fix.clip(lower=0).median()), 1),
        "met_target_pct": round(float((fixed.sla_met == "Y").mean()), 3),
        "road_matched_pct_open": round(float(iss[iss.status == "never_fixed"].road_id.notna().mean()), 3),
        "social_posts": len(posts),
        "social_posts_linked": int(posts.issue_id.notna().sum()),
        "social_post_kinds": posts.kind.value_counts().to_dict(),
        "social_linked_by_kind": posts[posts.issue_id.notna()].kind.value_counts().to_dict(),
    }


def write(iss: pd.DataFrame, summary: dict) -> None:
    records = []
    for r in iss.itertuples():
        ts = lambda x: None if pd.isna(x) else x.isoformat(timespec="minutes")  # noqa: E731
        records.append(
            {
                "issue_id": r.issue_id,
                "complaint_ids": r.complaint_ids,
                "social_post_ids": r.social_post_ids,
                "ward_code": r.ward_code,
                "locality": r.locality,
                "lat": None if pd.isna(r.lat) else round(float(r.lat), 5),
                "lon": None if pd.isna(r.lon) else round(float(r.lon), 5),
                "category": r.category,
                "first_reported_at": ts(r.first_reported_at),
                "status": r.status,
                "work_order_ids": r.work_order_ids,
                "plan_issue_id": r.plan_issue_id if isinstance(r.plan_issue_id, str) else None,
                "trail": r.trail,
                "road_id": r.road_id if isinstance(r.road_id, str) else None,
                "road_name": r.road_name if isinstance(r.road_name, str) else None,
                "n_complaints": int(r.n_complaints),
                "channels": r.channels,
                "languages": r.languages,
                "upvotes": int(r.upvotes),
                "disposition": r.disposition if isinstance(r.disposition, str) else None,
                "work_order": None
                if not r.work_order_ids
                else {
                    "work_order_id": r.work_order_id,
                    "contractor_id": r.contractor_id,
                    "contractor_name": r.contractor_name,
                    "repair_method": r.repair_method,
                    "cost_inr": int(r.cost_inr),
                    "completed_at": ts(r.completed_at),
                    "days_to_fix": None if pd.isna(r.days_to_fix) else round(float(r.days_to_fix), 1),
                    "sla_hours": int(r.sla_hours),
                    "sla_met": r.sla_met == "Y",
                    "reopened_within_30d": r.reopened_within_30d == "Y",
                    "flags": r.flag_types,
                },
            }
        )
    write_json("issues", records, compact=True)
    write_json("issues_summary", summary)
